import fs from 'node:fs';
import path from 'node:path';

/**
 * Merges verified product-copy rewrites into lib/catalog/product-copy.generated.ts.
 *
 * Usage: node scripts/merge-product-copy.mjs <rewrite-dir>
 *   <rewrite-dir>/out/*.json   writer output (arrays of copy objects)
 *   <rewrite-dir>/failures.json  ids rejected by check.mjs (excluded here)
 *
 * Only entries that passed every check are merged; everything else keeps the
 * fallback overview. Existing entries for other ids are preserved, so batches
 * can be merged incrementally.
 */
const dir = process.argv[2];
if (!dir) throw new Error('Usage: node scripts/merge-product-copy.mjs <rewrite-dir>');

const target = new URL('../lib/catalog/product-copy.generated.ts', import.meta.url);
const existing = fs.readFileSync(target, 'utf8').match(/export const productCopy: Record<string, ProductCopy> = (\{[\s\S]*\});\s*$/);
const merged = existing ? JSON.parse(existing[1]) : {};

const failed = new Set(JSON.parse(fs.readFileSync(path.join(dir, 'failures.json'), 'utf8')).map((f) => f.id));
const clean = (list) => (Array.isArray(list) ? list.filter((item) => typeof item === 'string' && item.trim()) : []);
let added = 0;
let skipped = 0;
for (const file of fs.readdirSync(path.join(dir, 'out')).filter((name) => name.endsWith('.json')).sort()) {
  for (const entry of JSON.parse(fs.readFileSync(path.join(dir, 'out', file), 'utf8'))) {
    if (failed.has(entry.id)) { skipped++; continue; }
    merged[entry.id] = {
      intro: entry.intro.trim(),
      benefits: clean(entry.benefits),
      features: clean(entry.features),
      idealUse: entry.idealUse.trim(),
      included: clean(entry.included),
      cta: entry.cta.trim(),
    };
    added++;
  }
}

fs.writeFileSync(
  target,
  `/* Generated by scripts/merge-product-copy.mjs from verified rewrites. Do not edit by hand. */\nimport type { ProductCopy } from './product-copy';\n\nexport const productCopy: Record<string, ProductCopy> = ${JSON.stringify(merged, null, 1)};\n`,
);
console.log(`Merged ${added} verified entries (${skipped} failed checks skipped); ${Object.keys(merged).length} products now have copy.`);
