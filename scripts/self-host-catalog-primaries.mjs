import fs from 'node:fs';

/**
 * Copies the primary product photos stored in Git LFS (public/catalog/) into
 * public/media/catalog/, outside the LFS pattern, so Vercel serves them from
 * this domain instead of GitHub's LFS media endpoint (which has a monthly
 * bandwidth cap and is not meant as a website CDN). Same files, unchanged.
 * Gallery photos stay in LFS. Run after a build (reads the built feed):
 *
 *   node scripts/self-host-catalog-primaries.mjs
 *
 * Files not checked out locally (LFS pointers) are fetched from this
 * repository's LFS media. Writes lib/catalog/self-hosted-catalog.generated.ts,
 * the list of copied files; earlier entries are kept.
 */
const root = new URL('../', import.meta.url);
const feed = new URL('dist/client/feeds/google-merchant-products.tsv', root);
const source = new URL('public/catalog/', root);
const target = new URL('public/media/catalog/', root);
const listFile = new URL('lib/catalog/self-hosted-catalog.generated.ts', root);
const lfsHost = 'https://media.githubusercontent.com/';

const [head, ...lines] = fs.readFileSync(feed, 'utf8').trim().split('\n');
const imageColumn = head.split('\t').indexOf('image_link');
const urls = [...new Set(lines.map((line) => line.split('\t')[imageColumn]).filter((url) => url.startsWith(lfsHost)))];

const previous = fs.existsSync(listFile)
  ? JSON.parse(fs.readFileSync(listFile, 'utf8').match(/\((\[[\s\S]*\])\)/)?.[1] ?? '[]')
  : [];
const copied = new Set(previous);
let missing = 0;
fs.mkdirSync(target, { recursive: true });
for (const url of urls) {
  const name = url.split('/').pop();
  const from = new URL(name, source);
  // An LFS pointer file (not checked out) is a few hundred bytes of text.
  if (fs.existsSync(from) && fs.statSync(from).size >= 1000) {
    fs.copyFileSync(from, new URL(name, target));
    copied.add(name);
    continue;
  }
  try {
    const res = await fetch(url);
    const type = res.headers.get('content-type') ?? '';
    const buf = Buffer.from(await res.arrayBuffer());
    if (!res.ok || !type.startsWith('image/') || buf.length < 1000) throw new Error(`${res.status} ${type}`);
    fs.writeFileSync(new URL(name, target), buf);
    copied.add(name);
  } catch (error) {
    missing++;
    console.warn(`could not get ${name}: ${error.message}`);
  }
}
fs.writeFileSync(
  listFile,
  `// Generated by scripts/self-host-catalog-primaries.mjs. Do not edit.\n` +
    `/** Catalog photos also copied to public/media/catalog/ (served by Vercel, not LFS). */\n` +
    `export const selfHostedCatalogImages = new Set<string>(${JSON.stringify([...copied].sort(), null, 1)});\n`,
);
console.log(`Catalog primaries on this domain: ${copied.size} (${urls.length} were on LFS media); ${missing} failed.`);
