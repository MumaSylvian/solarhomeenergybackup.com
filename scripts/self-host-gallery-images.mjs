import crypto from 'node:crypto';
import fs from 'node:fs';

/**
 * Copy active product gallery images into first-party storage. The Merchant
 * feed is the source of truth here, so excluded/unsellable catalog records are
 * not downloaded. Files are content-addressed by source URL and the original
 * extension, making retries safe and preventing collisions between supplier
 * image variants that share a product UUID.
 */
const root = new URL('../', import.meta.url);
const feed = new URL('dist/client/feeds/google-merchant-products.tsv', root);
const outDir = new URL('public/media/gallery/', root);
const mapFile = new URL('lib/catalog/self-hosted-gallery.generated.ts', root);
const [, ...lines] = fs.readFileSync(feed, 'utf8').trim().split('\n');
const header = fs.readFileSync(feed, 'utf8').split('\n', 1)[0].split('\t');
const column = header.indexOf('additional_image_link');
const urls = [...new Set(lines.flatMap((line) => (line.split('\t')[column] ?? '').split(',').filter((url) => /^https?:\/\//i.test(url))))].sort();
const previous = fs.existsSync(mapFile)
  ? JSON.parse(fs.readFileSync(mapFile, 'utf8').match(/= (\{[\s\S]*\});/)?.[1] ?? '{}')
  : {};
const done = new Map(Object.entries(previous));
// `--repair-all` repairs files that were mapped by an earlier interrupted run
// but never made it into the checkout. This is intentionally opt-in so normal
// builds only mirror the active Merchant feed.
const allUrls = process.argv.includes('--repair-all')
  ? [...new Set([...urls, ...Object.keys(previous)])].sort()
  : urls;
fs.mkdirSync(outDir, { recursive: true });

const extensionFor = (url, type) => {
  const match = new URL(url).pathname.match(/\.(jpe?g|png|webp|gif|bmp|tiff?)$/i);
  if (match) return `.${match[1].toLowerCase().replace('jpeg', 'jpg').replace('tif', 'tiff')}`;
  if (type.includes('webp')) return '.webp';
  if (type.includes('png')) return '.png';
  if (type.includes('gif')) return '.gif';
  return '.jpg';
};
const fileFor = (url, type) => `${crypto.createHash('sha256').update(url).digest('hex').slice(0, 24)}${extensionFor(url, type)}`;
// Recover successful downloads if a long run is interrupted before its map is written.
for (const url of allUrls) {
  if (done.has(url)) {
    const mapped = done.get(url);
    if (mapped && fs.existsSync(new URL(mapped, outDir)) && fs.statSync(new URL(mapped, outDir)).size > 1000) continue;
    done.delete(url);
  }
  for (const ext of ['.jpg', '.png', '.webp', '.gif', '.bmp', '.tiff']) {
    const name = `${crypto.createHash('sha256').update(url).digest('hex').slice(0, 24)}${ext}`;
    if (fs.existsSync(new URL(name, outDir)) && fs.statSync(new URL(name, outDir)).size > 1000) {
      done.set(url, name);
      break;
    }
  }
}
if (process.argv.includes('--map-only')) {
  const entries = Object.fromEntries([...done].sort(([a], [b]) => a.localeCompare(b)));
  fs.writeFileSync(mapFile, `// Generated by scripts/self-host-gallery-images.mjs. Do not edit.\n/** Supplier gallery URL → first-party file in public/media/gallery/. */\nexport const selfHostedGalleryImages: Record<string, string> = ${JSON.stringify(entries, null, 1)};\n`);
  console.log(`Mapped ${done.size}/${urls.length} already-downloaded gallery images.`);
  process.exit(0);
}
const queue = allUrls.filter((url) => !done.has(url)).sort((a, b) => {
  const mediaA = a.includes('media.githubusercontent.com') ? 0 : 1;
  const mediaB = b.includes('media.githubusercontent.com') ? 0 : 1;
  return mediaA - mediaB || a.localeCompare(b);
});
let failed = 0;
const workers = Array.from({ length: Number(process.env.GALLERY_CONCURRENCY ?? 24) }, async () => {
  while (queue.length) {
    const url = queue.shift();
    if (!url) return;
    let success = false;
    for (let attempt = 0; attempt < 3 && !success; attempt++) {
      try {
        const response = await fetch(url, { headers: { 'user-agent': 'SolarHome-Merchant-Image-Mirror/1.0' } });
        const type = response.headers.get('content-type') ?? '';
        if (!response.ok || !type.startsWith('image/')) throw new Error(`${response.status} ${type}`);
        const data = Buffer.from(await response.arrayBuffer());
        if (data.length < 1000) throw new Error('image response too small');
        const name = fileFor(url, type);
        fs.writeFileSync(new URL(name, outDir), data);
        done.set(url, name);
        success = true;
      } catch (error) {
        if (attempt === 2) {
          failed++;
          console.warn(`failed ${url}: ${error.message}`);
        }
      }
    }
  }
});
await Promise.all(workers);
const entries = Object.fromEntries([...done].sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  mapFile,
  `// Generated by scripts/self-host-gallery-images.mjs. Do not edit.\n` +
    `/** Supplier gallery URL → first-party file in public/media/gallery/. */\n` +
    `export const selfHostedGalleryImages: Record<string, string> = ${JSON.stringify(entries, null, 1)};\n`,
);
console.log(`Self-hosted ${done.size}/${allUrls.length} gallery images; ${failed} failed.`);
