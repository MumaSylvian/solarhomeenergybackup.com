import fs from 'node:fs';

/**
 * Copies the primary product photos that are still hotlinked from a supplier
 * CDN into public/media/products/, so the storefront and the Merchant Center
 * feed serve them from this domain. Same photos, byte for byte; nothing is
 * edited. Run after a build (it reads image_link from the built feed):
 *
 *   node scripts/self-host-primary-images.mjs
 *
 * Writes lib/catalog/self-hosted-images.generated.ts, the list the catalog
 * uses to swap each hotlinked URL for its local copy. Only files that
 * downloaded completely are listed, so a failed download keeps the old URL.
 * public/media/ is deliberately outside the Git LFS pattern (public/catalog/**):
 * Vercel serves LFS pointer files, not the images.
 */
const root = new URL('../', import.meta.url);
const feed = new URL('dist/client/feeds/google-merchant-products.tsv', root);
const outDir = new URL('public/media/products/', root);
const listFile = new URL('lib/catalog/self-hosted-images.generated.ts', root);
const host = 'https://images.thdstatic.com/';

const [head, ...lines] = fs.readFileSync(feed, 'utf8').trim().split('\n');
const imageColumn = head.split('\t').indexOf('image_link');
const urls = [...new Set(lines.map((line) => line.split('\t')[imageColumn]).filter((url) => url.startsWith(host)))];

/** productImages/<uuid>/svn/<name>_600.jpg → <uuid>.jpg */
export const localNameFor = (url) => {
  const match = url.match(/productImages\/([0-9a-f-]{36})\/.*\.(jpe?g|png|webp)$/i);
  return match ? `${match[1]}.${match[2].toLowerCase()}` : null;
};

fs.mkdirSync(outDir, { recursive: true });
const done = new Map();
let failed = 0;
const queue = [...urls];
async function worker() {
  while (queue.length) {
    const url = queue.shift();
    const name = localNameFor(url);
    if (!name) { failed++; continue; }
    const file = new URL(name, outDir);
    if (fs.existsSync(file) && fs.statSync(file).size > 1000) { done.set(url, name); continue; }
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        const res = await fetch(url);
        const type = res.headers.get('content-type') ?? '';
        if (!res.ok || !type.startsWith('image/')) throw new Error(`${res.status} ${type}`);
        const buf = Buffer.from(await res.arrayBuffer());
        if (buf.length < 1000) throw new Error('too small');
        fs.writeFileSync(file, buf);
        done.set(url, name);
        break;
      } catch (error) {
        if (attempt === 2) { failed++; console.warn(`failed ${url}: ${error.message}`); }
      }
    }
  }
}
await Promise.all(Array.from({ length: 12 }, worker));

const entries = [...done].sort(([a], [b]) => a.localeCompare(b));
fs.writeFileSync(
  listFile,
  `// Generated by scripts/self-host-primary-images.mjs. Do not edit.\n` +
    `/** Supplier-CDN primary photo URL → file in public/media/products/. */\n` +
    `export const selfHostedImages: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 1)};\n`,
);
console.log(`Self-hosted ${done.size} of ${urls.length} primary images; ${failed} failed.`);
